"""Zone X E2E Acceptance Test:
- X1 Gate: Live headed window with --control-socket and --supervise-commits-only:
  - Routine non-secret fill_form auto-executes via commit_gate policy without blocking for glasses.
  - Sensitive fill_secret and submit emit proposal.pending with requires_glasses=True and freeze before commit.
  - Host approve resumes execution once.
- X2 Gate: Native Semantic X-Ray overlay, Vault Shield, Freeze Shield, and live-measured Engine Telemetry HUD
  captured in live-window PNG screenshot (include_screenshot=True).
- X3 Gate: Real ECDSA P-256 WebAuthn assertion generated by vault.rs only after Host approve,
  verified against signup_fixture.py's /api/webauthn/register and /api/webauthn/verify endpoints;
  wrong challenge, wrong origin/RP, replayed assertion, and rejected decision all fail;
  zero private keys or passwords leak anywhere.
"""

