def http_json(url: str, method: str = "GET", payload: dict | None = None) -> tuple[int, dict]:
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=5.0) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        try:
            body = e.read().decode("utf-8", errors="replace")
        finally:
            e.close()
        try:
            return e.code, json.loads(body)
        except Exception:
            return e.code, {"raw": body}


class ZoneXEngineSuperpowersE2ETest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(prefix="hermes-zonex-")
        self.tmpdir = Path(self.tmp.name)
        self.db_path = self.tmpdir / "zonex.sqlite3"
        self.vault_path = self.tmpdir / "vault.json"
        self.recall_path = self.tmpdir / "recall.json"
        self.audit_path = self.tmpdir / "audit.jsonl"
        self.sock_path = self.tmpdir / "control.sock"
        self.host_token_file = self.tmpdir / "host.token"
        self.agent_token_file = self.tmpdir / "agent.token"
        self.host_token = "host_token_zonex_9876543210"
        self.agent_token = "agent_token_zonex_1234567890"
        self.host_token_file.write_text(self.host_token, encoding="utf-8")
        self.agent_token_file.write_text(self.agent_token, encoding="utf-8")

        self.server = signup_fixture.start_server("127.0.0.1", 0, self.db_path)
        self.server_thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.server_thread.start()
        self.base_url = f"http://127.0.0.1:{self.server.server_port}"

    def tearDown(self) -> None:
        try:
            self.server.shutdown()
            self.server.server_close()
        finally:
            self.tmp.cleanup()

    def test_x1_x2_x3_headed_commits_only_xray_and_webauthn_p256(self) -> None:
        # 1. Request a fresh WebAuthn challenge from the fixture for socon2026.local
        status, ch_resp = http_json(
            f"{self.base_url}/api/webauthn/challenge?rp_id=socon2026.local"
        )
        self.assertEqual(status, 200)
        challenge = ch_resp["challenge"]
        self.assertTrue(len(challenge) >= 16)

        env = os.environ.copy()
        env["HERMES_VAULT_PATH"] = str(self.vault_path)
        env["HERMES_RECALL_PATH"] = str(self.recall_path)
        env["HERMES_AUDIT_PATH"] = str(self.audit_path)

        proc = subprocess.Popen(
            [
                str(HERMES_BIN),
                "--control-socket",
                str(self.sock_path),
                "--host-token-file",
                str(self.host_token_file),
                "--agent-token-file",
                str(self.agent_token_file),
                "--supervise-commits-only",
                "--xray",
                "--exit-after",
                "25",
            ],
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        try:
            deadline = time.monotonic() + 8.0
            while time.monotonic() < deadline and not self.sock_path.exists():
                time.sleep(0.05)
            self.assertTrue(self.sock_path.exists(), "Control socket did not appear")

            host = ControlClient(self.sock_path, self.host_token)
            agent = ControlClient(self.sock_path, self.agent_token)
            try:
                # Open session on /signup
                host.send(
                    {
                        "type": "session.open",
                        "request_id": "open-x",
                        "title": "Zone X Engine Verification",
                        "start_url": f"{self.base_url}/signup?challenge={challenge}&rp_id=socon2026.local",
                        "policy": {"decision": "human_per_action"},
                    }
                )
                opened = host.read_until_type("session.opened")
                session_id = opened["session_id"]

                # Wait for initial navigation to commit
                deadline_nav = time.monotonic() + 6.0
                obs = None
                while time.monotonic() < deadline_nav:
                    agent.send(
                        {
                            "type": "observe.request",
                            "request_id": "obs-1",
                            "session_id": session_id,
                            "include_screenshot": True,
                        }
                    )
                    frame = agent.read_until_type("observe.result")
                    els_list = frame.get("elements") or []
                    if any(
                        e.get("dom_id") == "speaker_name" or e.get("name") == "speaker_name"
                        for e in els_list
                    ):
                        obs = frame
                        break
                    time.sleep(0.08)
                self.assertIsNotNone(obs, "Did not observe /signup")

                # X2 Gate check: screenshot PNG bytes are valid and non-empty
                png_b64 = obs.get("screenshot_png_b64")
                self.assertTrue(png_b64 and len(png_b64) > 1000)
                png_bytes = base64.b64decode(png_b64)
                self.assertEqual(png_bytes[:8], b"\x89PNG\r\n\x1a\n")
                screenshot_file = self.tmpdir / "xray_live_window.png"
                screenshot_file.write_bytes(png_bytes)
                self.assertTrue(screenshot_file.stat().st_size > 2000)

                els = {
                    (e.get("dom_id") or e.get("name") or e.get("id")): e["id"]
                    for e in obs["elements"]
                    if e.get("dom_id") or e.get("name") or e.get("id")
                }

                # X1 Gate check 1: Routine non-secret fill_form auto-executes under --supervise-commits-only
                # WITHOUT requiring a Host decision!
                agent.send(
                    {
                        "type": "propose",
                        "request_id": "prop-routine",
                        "session_id": session_id,
                        "proposal_id": "p_routine_fill",
                        "snapshot_id": obs["snapshot_id"],
                        "fingerprint": obs["fingerprint"],
                        "generation": obs["generation"],
                        "rationale": "Fill non-secret speaker fields automatically",
                        "operation": {
                            "kind": "fill_form",
                            "fields": [
                                {"target_id": els["speaker_name"], "action": "type", "value": "Ryan Speaker"},
                                {"target_id": els["email"], "action": "type", "value": "ryan@socon.dev"},
                                {"target_id": els["talk_title"], "action": "type", "value": "Native Supervised Browsers"},
                                {"target_id": els["track"], "action": "select", "value": "ai_agents"},
                                {"target_id": els["live_demo"], "action": "check", "value": "true"},
                            ],
                        },
                    }
                )
                # Should immediately receive executed without needing host.send(decision)!
                exec_frame = agent.read_until_type("executed")
                self.assertEqual(exec_frame["proposal_id"], "p_routine_fill")

                # Observe updated DOM
                agent.send(
                    {
                        "type": "observe.request",
                        "request_id": "obs-2",
                        "session_id": session_id,
                        "include_screenshot": False,
                    }
                )
                obs2 = agent.read_until_type("observe.result")
                els2 = {
                    (e.get("dom_id") or e.get("name") or e.get("id")): e
                    for e in obs2["elements"]
                    if e.get("dom_id") or e.get("name") or e.get("id")
                }
                self.assertEqual(els2["speaker_name"]["value"], "Ryan Speaker")
                self.assertEqual(els2["email"]["value"], "ryan@socon.dev")

                # X1 & X3 Gate check 2: Propose fill_secret — first test REJECT prevents secret/passkey creation
                pw_id = els2["password"]["id"]
                agent.send(
                    {
                        "type": "propose",
                        "request_id": "prop-secret-reject",
                        "session_id": session_id,
                        "proposal_id": "p_secret_reject",
                        "snapshot_id": obs2["snapshot_id"],
                        "fingerprint": obs2["fingerprint"],
                        "generation": obs2["generation"],
                        "rationale": "Inject blind vault secret and sign WebAuthn assertion",
                        "operation": {
                            "kind": "fill_form",
                            "fields": [
                                {
                                    "target_id": pw_id,
                                    "action": "fill_secret",
                                    "origin": self.base_url,
                                    "username": "ryan@socon.dev",
                                }
                            ],
                        },
                    }
                )
                pending_secret = host.read_until_type("proposal.pending")
                self.assertEqual(pending_secret["proposal_id"], "p_secret_reject")
                self.assertTrue(
                    pending_secret.get("requires_glasses") is True,
                    "fill_secret must carry requires_glasses=True",
                )

                # Reject it and verify vault file was NOT created
                host.send(
                    {
                        "type": "decision",
                        "request_id": "dec-reject",
                        "session_id": session_id,
                        "proposal_id": "p_secret_reject",
                        "fingerprint": obs2["fingerprint"],
                        "generation": obs2["generation"],
                        "decision": "reject",
                        "decided_by": "user",
                        "surface": "glasses_dat",
                    }
                )
                inv = agent.read_until_type("proposal.invalidated")
                self.assertEqual(inv["reason"], "rejected")
                self.assertFalse(
                    self.vault_path.exists(),
                    "Rejected fill_secret must not create vault credentials or sign passkey",
                )

                # Re-observe and propose fill_secret again, this time APPROVING
                agent.send(
                    {
                        "type": "observe.request",
                        "request_id": "obs-3",
                        "session_id": session_id,
                        "include_screenshot": True,
                    }
                )
                obs3 = agent.read_until_type("observe.result")
                agent.send(
                    {
                        "type": "propose",
                        "request_id": "prop-secret-approve",
                        "session_id": session_id,
                        "proposal_id": "p_secret_approve",
                        "snapshot_id": obs3["snapshot_id"],
                        "fingerprint": obs3["fingerprint"],
                        "generation": obs3["generation"],
                        "rationale": "Inject blind vault secret and sign WebAuthn assertion",
                        "operation": {
                            "kind": "fill_form",
                            "fields": [
                                {
                                    "target_id": pw_id,
                                    "action": "fill_secret",
                                    "origin": self.base_url,
                                    "username": "ryan@socon.dev",
                                }
                            ],
                        },
                    }
                )
                pending_secret2 = host.read_until_type("proposal.pending")
                self.assertTrue(pending_secret2.get("requires_glasses") is True)

                host.send(
                    {
                        "type": "decision",
                        "request_id": "dec-approve-secret",
                        "session_id": session_id,
                        "proposal_id": "p_secret_approve",
                        "fingerprint": obs3["fingerprint"],
                        "generation": obs3["generation"],
                        "decision": "approve",
                        "decided_by": "user",
                        "surface": "glasses_dat",
                    }
                )
                exec_secret = agent.read_until_type("executed")
                self.assertEqual(exec_secret["proposal_id"], "p_secret_approve")

                # Verify vault created both password secret AND P-256 keypair
                vault_data = json.loads(self.vault_path.read_text(encoding="utf-8"))
                self.assertEqual(len(vault_data["accounts"]), 1)
                acct = vault_data["accounts"][0]
                secret_pw = acct["secret"]
                priv_pem = acct["private_key_pem"]
                pub_pem = acct["public_key_pem"]
                cred_id = acct["credential_id"]
                self.assertIn("BEGIN PRIVATE KEY", priv_pem)
                self.assertIn("BEGIN PUBLIC KEY", pub_pem)

                # Now propose submit (requires_glasses=True)
                agent.send(
                    {
                        "type": "observe.request",
                        "request_id": "obs-4",
                        "session_id": session_id,
                        "include_screenshot": True,
                    }
                )
                obs4 = agent.read_until_type("observe.result")
                submit_id = next(
                    e["id"]
                    for e in obs4["elements"]
                    if e.get("dom_id") == "submit-btn" or e.get("tag") == "button"
                )
                agent.send(
                    {
                        "type": "propose",
                        "request_id": "prop-submit",
                        "session_id": session_id,
                        "proposal_id": "p_submit_1",
                        "snapshot_id": obs4["snapshot_id"],
                        "fingerprint": obs4["fingerprint"],
                        "generation": obs4["generation"],
                        "rationale": "Submit speaker account registration",
                        "operation": {"kind": "submit", "target_id": submit_id},
                    }
                )
                pending_sub = host.read_until_type("proposal.pending")
                self.assertEqual(pending_sub["proposal_id"], "p_submit_1")
                self.assertTrue(
                    pending_sub.get("requires_glasses") is True,
                    "submit must carry requires_glasses=True",
                )

                # Verify account is STILL 0 before host approves submit (hard freeze gate)
                st_acc, acc_before = http_json(f"{self.base_url}/api/accounts")
                self.assertEqual(st_acc, 200)
                self.assertEqual(len(acc_before["accounts"]), 0)

                # Host approves submit
                host.send(
                    {
                        "type": "decision",
                        "request_id": "dec-approve-submit",
                        "session_id": session_id,
                        "proposal_id": "p_submit_1",
                        "fingerprint": obs4["fingerprint"],
                        "generation": obs4["generation"],
                        "decision": "approve",
                        "decided_by": "user",
                        "surface": "glasses_dat",
                    }
                )
                exec_sub = agent.read_until_type("executed")
                self.assertEqual(exec_sub["proposal_id"], "p_submit_1")

                # Verify account row exists in SQLite
                _, acc_after = http_json(f"{self.base_url}/api/accounts")
                self.assertEqual(len(acc_after["accounts"]), 1)

                # X3 Gate: Register the vault's public key with the fixture RP and verify a real
                # P-256 WebAuthn assertion (plus test wrong challenge, wrong RP, and replay failure)
                reg_status, reg_resp = http_json(
                    f"{self.base_url}/api/webauthn/register",
                    method="POST",
                    payload={
                        "credential_id": cred_id,
                        "public_key_pem": pub_pem,
                        "rp_id": "socon2026.local",
                        "user_email": "ryan@socon.dev",
                    },
                )
                self.assertEqual(reg_status, 200)
                self.assertTrue(reg_resp.get("ok"))

                # Construct a real WebAuthn assertion signed by the vault's P-256 private key
                # matching vault::sign_webauthn_assertion's exact layout
                import hashlib

                client_data_bytes = json.dumps(
                    {
                        "type": "webauthn.get",
                        "challenge": challenge,
                        "origin": self.base_url,
                        "crossOrigin": False,
                    },
                    separators=(",", ":"),
                ).encode("utf-8")
                rp_hash = hashlib.sha256(b"socon2026.local").digest()
                auth_data = rp_hash + bytes([0x05]) + (1).to_bytes(4, "big")
                signed_payload = auth_data + hashlib.sha256(client_data_bytes).digest()

                priv_file = self.tmpdir / "priv.pem"
                priv_file.write_text(priv_pem, encoding="utf-8")
                sig_der = subprocess.check_output(
                    ["openssl", "dgst", "-sha256", "-sign", str(priv_file)],
                    input=signed_payload,
                )

                assertion_payload = {
                    "credential_id": cred_id,
                    "rp_id": "socon2026.local",
                    "origin": self.base_url,
                    "authenticator_data_b64": base64.b64encode(auth_data).decode("ascii"),
                    "client_data_json_b64": base64.b64encode(client_data_bytes).decode("ascii"),
                    "signature_der_b64": base64.b64encode(sig_der).decode("ascii"),
                }

                # 1) Wrong origin/RP must fail
                bad_origin_status, _ = http_json(
                    f"{self.base_url}/api/webauthn/verify",
                    method="POST",
                    payload={**assertion_payload, "origin": "http://evil.example"},
                )
                self.assertEqual(bad_origin_status, 400)

                # 2) Valid assertion must succeed
                ok_status, ok_resp = http_json(
                    f"{self.base_url}/api/webauthn/verify",
                    method="POST",
                    payload=assertion_payload,
                )
                self.assertEqual(ok_status, 200, f"WebAuthn verify failed: {ok_resp}")
                self.assertTrue(ok_resp.get("verified"))

                # 3) Replaying the exact same assertion must fail (single-use challenge)
                replay_status, _ = http_json(
                    f"{self.base_url}/api/webauthn/verify",
                    method="POST",
                    payload=assertion_payload,
                )
                self.assertEqual(replay_status, 400)

                # Verify zero secret/private-key leaks across all socket frames and audit log
                combined = (
                    "\n".join(host.raw_lines)
                    + "\n"
                    + "\n".join(agent.raw_lines)
                    + "\n"
                    + (self.audit_path.read_text(encoding="utf-8") if self.audit_path.exists() else "")
                )
                self.assertNotIn(secret_pw, combined)
                self.assertNotIn("BEGIN PRIVATE KEY", combined)
            finally:
                host.close()
                agent.close()
        finally:
            proc.terminate()
            try:
                proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                proc.kill()
            if proc.stdout:
                proc.stdout.close()
            if proc.stderr:
                proc.stderr.close()


if __name__ == "__main__":
    unittest.main(verbosity=2)
